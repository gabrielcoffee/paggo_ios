/// Regras de dia útil (fim de semana + feriados bancários brasileiros), espelhando
/// `formatPaymentDate` de @paggo/core-utils. A lista de feriados (2023–2099) é portada de
/// packages/paggo-core-utils/src/date/constants.ts — chaves yyyymmdd.
enum BusinessDay {
    private static var utcCalendar: Calendar {
        var c = Calendar(identifier: .gregorian)
        c.timeZone = TimeZone(identifier: "UTC")!
        return c
    }

    private static let holidays: Set<Int> = Set(
        rawHolidays.split(separator: ",").compactMap { Int($0) }
    )

    /// Sábado (7) ou domingo (1) no calendário gregoriano.
    static func isWeekend(weekday: Int) -> Bool { weekday == 1 || weekday == 7 }

    static func isHoliday(year: Int, month: Int, day: Int) -> Bool {
        holidays.contains(year * 10000 + month * 100 + day)
    }

    /// Extrai ano/mês/dia do prefixo `yyyy-MM-dd` de uma string ISO (em UTC, como o luxon do web).
    private static func ymd(_ iso: String) -> (Int, Int, Int)? {
        let chars = Array(iso)
        guard chars.count >= 10, chars[4] == "-", chars[7] == "-",
              let y = Int(String(chars[0..<4])),
              let m = Int(String(chars[5..<7])),
              let d = Int(String(chars[8..<10])) else { return nil }
        return (y, m, d)
    }

    /// Data de pagamento formatada `dd/MM/yy` + o delta de dias úteis (`+N`) quando a data cai em
    /// fim de semana ou feriado bancário (o pagamento real ocorre no próximo dia útil). Espelha
    /// `formatPaymentDate({ considerWorkingDays: true })`.
    static func paymentDate(fromISO iso: String) -> (text: String, plusDays: Int?) {
        guard let (y, m, d) = ymd(iso) else { return ("—", nil) }
        let text = String(format: "%02d/%02d/%02d", d, m, y % 100)
        let cal = utcCalendar
        guard var cur = cal.date(from: DateComponents(year: y, month: m, day: d)) else {
            return (text, nil)
        }
        func nonBusiness(_ date: Date) -> Bool {
            let c = cal.dateComponents([.year, .month, .day, .weekday], from: date)
            guard let wd = c.weekday, let yy = c.year, let mm = c.month, let dd = c.day else { return false }
            return isWeekend(weekday: wd) || isHoliday(year: yy, month: mm, day: dd)
        }
        guard nonBusiness(cur) else { return (text, nil) }
        var delta = 0
        while nonBusiness(cur) {
            cur = cal.date(byAdding: .day, value: 1, to: cur) ?? cur
            delta += 1
            if delta > 30 { break }
        }
        return (text, delta)
    }

